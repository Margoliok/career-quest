export type Key = keyof typeof D

interface Ctx { lang: Lang; setLang: (l: Lang) => void; t: (k: Key) => string }
const I18n = createContext<Ctx>({ lang: 'kk', setLang: () => {}, t: (k) => D[k].kk })

function initialLang(): Lang {
  try { const v = localStorage.getItem('cq_lang'); if (v === 'ru' || v === 'kk') return v } catch { /* ignore */ }
  return 'kk'
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(initialLang)
  const setLang = (l: Lang) => { setLangState(l); try { localStorage.setItem('cq_lang', l) } catch { /* ignore */ } }
  const t = (k: Key) => D[k]?.[lang] ?? String(k)
  return <I18n.Provider value={{ lang, setLang, t }}>{children}</I18n.Provider>
}

export const useI18n = () => useContext(I18n)

export function roleTitle(r: { title_kk: string; title_ru: string } | null | undefined, lang: Lang) {
  if (!r) return '—'
  return lang === 'kk' ? r.title_kk : r.title_ru
}
